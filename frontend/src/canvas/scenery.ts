/** The vector form, unchanged — still the path taken above zoom 1 and without a canvas. */
function drawTrafficLightVector(ctx: CanvasRenderingContext2D, L: Light, d: SceneDraw): void {
  const { isDark, time } = d;
  const x = L.x, y = L.y;
  ctx.save();
  ctx.translate(x, y);
  ctx.fillStyle = "rgba(0,0,0,0.12)";
  ctx.beginPath(); ctx.ellipse(0, 0, 5, 2.2, 0, 0, Math.PI * 2); ctx.fill();
  ctx.strokeStyle = isDark ? "#4a4741" : "#3c3a35";
  ctx.lineWidth = 2.6;
  ctx.beginPath(); ctx.moveTo(0, 0); ctx.lineTo(0, -30); ctx.stroke();
  ctx.fillStyle = isDark ? "#26241f" : "#2b2a26";
  ctx.fillRect(-6, -54, 12, 25);
  ctx.strokeStyle = isDark ? "#8a857c" : "#1b1915";
  ctx.lineWidth = 0.9;
  ctx.strokeRect(-6, -54, 12, 25);
  const states: Record<LightState, string> = { red: "#e0402f", yellow: "#e8b83a", green: "#3ab35a" };
  const hS = lightState(time, "h");
  const vS = lightState(time, "v");
  const order: LightState[] = ["red", "yellow", "green"];
  order.forEach((st, i) => {
    const cy = -48.5 + i * 7.5;
    const lit = st === hS; // this lamp faces the horizontal road
    ctx.globalAlpha = lit ? 1 : 0.3;
    ctx.fillStyle = states[st];
    ctx.beginPath(); ctx.arc(0, cy, 3.3, 0, Math.PI * 2); ctx.fill();
    if (lit) {
      ctx.globalAlpha = 0.38;
      ctx.beginPath(); ctx.arc(0, cy, 6, 0, Math.PI * 2); ctx.fill();
    }
  });
  ctx.globalAlpha = 1;
  // v-road indicator on the side
  ctx.fillStyle = states[vS];
  ctx.globalAlpha = 0.95;
  ctx.fillRect(7.5, -46, 3.4, 3.4);
  ctx.globalAlpha = 1;
  ctx.restore();
}

function drawVehicle(ctx: CanvasRenderingContext2D, v: Vehicle, d: SceneDraw): void {
  const { isDark, night } = d;
  ctx.save();
  ctx.translate(v.x, v.y);
  let ang = 0;
  if (v.axis === "v") ang = v.fy >= 0 ? Math.PI / 2 : -Math.PI / 2;
  else ang = v.fx >= 0 ? 0 : Math.PI;
  ctx.rotate(ang);
  // per-kind dimensions: long body for bus/truck, stretched for van/pickup
  const isLong = v.kind === "bus" || v.kind === "truck";
  const isStretch = v.kind === "van" || v.kind === "pickup";
  const half = isLong ? 20 : isStretch ? 17 : 14;
  const hw = isLong ? 7 : 6;
  // shadow
  ctx.fillStyle = "rgba(0,0,0,0.14)";
  ctx.beginPath();
  ctx.ellipse(0, 2, half + 1, hw + 2, 0, 0, Math.PI * 2);
  ctx.fill();
  // wheels (extra middle axle for long bodies)
  ctx.fillStyle = "#1e1a18";
  const wxF = half - 4, wxR = -half + 1;
  ctx.fillRect(wxR, -hw - 1.5, 5, 2.5);
  ctx.fillRect(wxF - 4, -hw - 1.5, 5, 2.5);
  ctx.fillRect(wxR, hw - 1, 5, 2.5);
  ctx.fillRect(wxF - 4, hw - 1, 5, 2.5);
  if (isLong) {
    ctx.fillRect(-2, -hw - 1.5, 5, 2.5);
    ctx.fillRect(-2, hw - 1, 5, 2.5);
  }
  // body
  ctx.fillStyle = v.color;
  roundRectLocal(ctx, -half, -hw, half * 2, hw * 2, 3);
  ctx.fill();
  if (v.kind === "bus") {
    // window band along the flank
    ctx.fillStyle = isDark ? "#2e3a44" : "#bcd4e2";
    ctx.fillRect(-half + 4, -hw + 1.5, half * 2 - 10, 3);
    ctx.fillRect(-half + 4, hw - 4.5, half * 2 - 10, 3);
  } else if (v.kind === "truck") {
    // cab + cargo split
    ctx.fillStyle = isDark ? "rgba(0,0,0,0.35)" : "rgba(0,0,0,0.18)";
    ctx.fillRect(half - 9, -hw, 1.5, hw * 2);
    ctx.strokeStyle = isDark ? "rgba(255,255,255,0.15)" : "rgba(0,0,0,0.12)";
    ctx.lineWidth = 0.8;
    for (let lx = -half + 5; lx < half - 10; lx += 5) {
      ctx.beginPath(); ctx.moveTo(lx, -hw + 1); ctx.lineTo(lx, hw - 1); ctx.stroke();
    }
  } else if (v.kind === "pickup") {
    // open bed at the rear
    ctx.fillStyle = isDark ? "rgba(0,0,0,0.45)" : "rgba(0,0,0,0.25)";
    roundRectLocal(ctx, -half + 2, -hw + 1.5, 9, hw * 2 - 3, 1.5);
    ctx.fill();
  }
  // roof (shorter on bus/truck — cab roof only)
  ctx.fillStyle = isDark ? "rgba(0,0,0,0.35)" : "rgba(0,0,0,0.18)";
  if (isLong) roundRectLocal(ctx, half - 12, -hw + 1, 9, hw * 2 - 2, 2);
  else roundRectLocal(ctx, -6, -5, 13, 10, 2);
  ctx.fill();
  // taxi roof sign
  if (v.kind === "taxi") {
    ctx.fillStyle = isDark ? "#2b2a26" : "#1b1915";
    ctx.fillRect(-2, -2.5, 5, 5);
    ctx.fillStyle = "#ffe9a8";
    ctx.fillRect(-1.4, -1.9, 3.8, 3.8);
  }
  // windshield + rear glass
  ctx.fillStyle = isDark ? "#2e3a44" : "#bcd4e2";
  ctx.fillRect(half - 7, -4.5, 3.5, 9);
  ctx.fillRect(-half + 5, -4.5, 2.5, 9);
  // headlights / taillights
  if (night > 0.1) {
    ctx.fillStyle = "rgba(255,240,180,0.95)";
  } else {
    ctx.fillStyle = "rgba(255,244,200,0.8)";
  }
  ctx.fillRect(half - 1, -5, 1.6, 3);
  ctx.fillRect(half - 1, 2, 1.6, 3);
  ctx.fillStyle = "#c03a2a";
  ctx.fillRect(-half - 0.4, -5, 1.4, 3);
  ctx.fillRect(-half - 0.4, 2, 1.4, 3);
  ctx.restore();

  // headlight beams at night
  if (night > 0.12) {
    ctx.save();
    ctx.translate(v.x, v.y);
    let ang2 = 0;
    if (v.axis === "v") ang2 = v.fy >= 0 ? Math.PI / 2 : -Math.PI / 2;
    else ang2 = v.fx >= 0 ? 0 : Math.PI;
    ctx.rotate(ang2);
    const grad = ctx.createLinearGradient(14, 0, 52, 0);
    grad.addColorStop(0, `rgba(255,240,190,${0.35 * night})`);
    grad.addColorStop(1, "rgba(255,240,190,0)");
    ctx.fillStyle = grad;
    ctx.beginPath();
    ctx.moveTo(14, -5);
    ctx.lineTo(52, -14);
    ctx.lineTo(52, 14);
    ctx.lineTo(14, 5);
    ctx.closePath();
    ctx.fill();
    ctx.restore();
  }
}

function roundRectLocal(ctx: CanvasRenderingContext2D, x: number, y: number, w: number, h: number, r: number): void {
  ctx.beginPath();
  ctx.moveTo(x + r, y);
  ctx.arcTo(x + w, y, x + w, y + h, r);
  ctx.arcTo(x + w, y + h, x, y + h, r);
  ctx.arcTo(x, y + h, x, y, r);
  ctx.arcTo(x, y, x + w, y, r);
  ctx.closePath();
}

export function pushScenery(queue: QueueItem[], ctx: CanvasRenderingContext2D, view: View, d: SceneDraw): void {
  const inView = (x: number, y: number) => x > view.l && x < view.r && y > view.t && y < view.b;

  // One detail level for the whole scenery pass. drawTree's full form is a
  // shadow, a transform and three tiered canopies — a handful of beginPath/fill
  // a tree — while drawTreeCheap is one ellipse and one disc. The difference
  // only shows when the crown is large enough to hold it, which the threshold
  // checks once per frame rather than once per tree.
  const fullDetail = (view.zoom ?? 1) >= TREE_DETAIL_MIN_ZOOM;
  // frameZoom is deliberately NOT written here. The raster cache needs the zoom,
  // but a push is not a draw: two queues can be pushed before either is drawn,
  // so recording it here would let the second push re-point the first draw's
  // sprite resolution. drawQueue sets it, immediately before the items run.

  // Every entry below is a pooled reference, not a closure: see QueueItem for
  // why. `ctx` and `d` are deliberately NOT captured — runItem takes them as
  // arguments at draw time, so a queued entry stays valid even if the caller
  // changes theme between the push and the draw.
  for (let i = 0; i < TREES.length; i++) {
    const t = TREES[i]!;
    if (!inView(t.x, t.y)) continue;
    const it = takeItem();
    it.y = t.y; it.kind = QK_TREE; it.idx = i;
    queue.push(it);
  }
  for (let i = 0; i < PROPS.length; i++) {
    const p = PROPS[i]!;
    if (!inView(p.x, p.y)) continue;
    const it = takeItem();
    it.y = p.y; it.kind = QK_PROP; it.idx = i;
    queue.push(it);
  }
  for (let i = 0; i < SCATTER.length; i++) {
    const p = SCATTER[i]!;
    if (!inView(p.x, p.y)) continue;
    const it = takeItem();
    it.y = p.y; it.kind = QK_SCATTER; it.idx = i;
    queue.push(it);
  }
  for (let i = 0; i < LIGHTS.length; i++) {
    const L = LIGHTS[i]!;
    if (!inView(L.x, L.y)) continue;
    const it = takeItem();
    it.y = L.y; it.kind = QK_LIGHT; it.idx = i;
    queue.push(it);
  }
  for (let i = 0; i < VEHICLES.length; i++) {
    const v = VEHICLES[i]!;
    if (!inView(v.x, v.y)) continue;
    const it = takeItem();
    it.y = v.y; it.kind = QK_VEHICLE; it.idx = i;
    queue.push(it);
  }
}
