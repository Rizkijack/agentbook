// Intersections of h-road and v-road -> traffic lights
interface Light { ix: number; iy: number; cx: number; cy: number; x: number; y: number; }
const H_ROADS = CORE_ROADS.filter((r) => r.y2 - r.y1 < r.x2 - r.x1);
const V_ROADS = CORE_ROADS.filter((r) => r.x2 - r.x1 <= r.y2 - r.y1);

export const LIGHTS: Light[] = [];
for (const h of H_ROADS) {
  for (const v of V_ROADS) {
    if (v.x1 <= h.x2 && v.x2 >= h.x1 && v.y1 <= h.y2 && v.y2 >= h.y1) {
      const ix = v.x1, iy = h.y1;
      LIGHTS.push({
        ix, iy,
        cx: (ix + 1) * V, cy: (iy + 1) * V,
        x: ix * V - 8, y: iy * V - 8,
      });
    }
  }
}

/**
 * A deterministic [0,1) hash. Every tree, prop and vehicle offset comes from
 * here, so the world is byte-identical each frame and across reloads.
 *
 * The shifts are LOGICAL and the multiply wraps as an unsigned 32-bit value,
 * and that matters more than it looks. With the arithmetic `>>` this returned a
 * uniform value on [0, 0.5) and never anything above it: measured over the
 * 74,550 tree candidates the deciles were 20.06 20.07 19.99 19.86 20.02 0 0 0 0
 * 0. The final xor always came back with its sign bit already cleared, so the
 * trailing `>>> 0` could not reach the upper half of the range at all.
 *
 * Every probability in this file was written as if that were uniform [0,1), so
 * they were all silently doubled, and any threshold of 0.5 or above was not a
 * probability at all - it was "always". `forestDensity` returning 0.62 for a
 * park measured as 0.958 survival, and 0.3 for open country measured as 0.567.
 * Thresholds here are now real probabilities and mean what they say.
 */
function h2(x: number, y: number): number {
  let n = (x * 374761393 + y * 668265263) | 0;
  n = ((n ^ (n >>> 13)) * 1274126177) >>> 0;
  return ((n ^ (n >>> 16)) >>> 0) / 4294967295;
}

function insideRect(tx: number, ty: number, r: { x: number; y: number; w: number; h: number }, m: number): boolean {
  return tx >= r.x - m && tx < r.x + r.w + m && ty >= r.y - m && ty < r.y + r.h + m;
}

function onRoad(tx: number, ty: number, m: number): boolean {
  for (const r of ROADS) {
    if (tx >= r.x1 - m && tx <= r.x2 + m && ty >= r.y1 - m && ty <= r.y2 + m) return true;
  }
  return false;
}

function onBuilding(tx: number, ty: number, m: number): boolean {
  for (const l of LOCATIONS) {
    if (insideRect(tx, ty, l, m)) return true;
  }
  return false;
}

/**
 * Tiles a tree or a prop may not stand on, baked once.
 *
 * natureFree() asked "is this tile on a road or in a building" by scanning all
 * 35 road rects and all 100 footprints. That is 135 comparisons per candidate,
 * and the 5x grid has ~74k candidates — about 10M comparisons before the first
 * frame, which is the page's whole load budget spent on a boolean. The answer
 * depends only on the tile, so it is precomputed.
 */
const BLOCKED: Uint8Array = (() => {
  const m = new Uint8Array(Pe * vt);
  const mark = (x0: number, y0: number, x1: number, y1: number) => {
    for (let y = Math.max(0, y0); y <= Math.min(vt - 1, y1); y++) {
      for (let x = Math.max(0, x0); x <= Math.min(Pe - 1, x1); x++) m[y * Pe + x] = 1;
    }
  };
  for (const r of ROADS) mark(r.x1 - 1, r.y1 - 1, r.x2 + 1, r.y2 + 1);
  // Driveways are walkable ground, so nothing plants on them either. Without
  // this a pine stands in the middle of a lane at the same probability as in
  // open country, and the driveway reads as a mistake rather than a driveway.
  for (const s of ACCESS_SPURS) {
    mark(Math.min(s.x1, s.x2) - 1, Math.min(s.y1, s.y2) - 1, Math.max(s.x1, s.x2) + 1, Math.max(s.y1, s.y2) + 1);
  }
  for (const l of LOCATIONS) mark(l.x - 1, l.y - 1, l.x + l.w, l.y + l.h);
  return m;
})();

function natureFree(tx: number, ty: number): boolean {
  // bounds come from the grid, not from a second copy of it — a hard-coded
  // `tx > 207` silently walled the forest into the old 210x128 world
  if (tx < 2 || ty < 2 || tx > Pe - 3 || ty > vt - 3) return false;
  return BLOCKED[ty * Pe + tx] === 0;
}

