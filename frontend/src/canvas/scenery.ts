export function drawTerrainDecor(ctx: CanvasRenderingContext2D, view: View, d: SceneDraw): void {
  const { isDark } = d;

  // The ground inside the city.
  //
  // This was a 20%-alpha tan wash laid over the base `--field`, so most of the
  // lawn still showed through it and every block interior stayed green. Inside a
  // street grid the ground is not lawn: it is paved lot, courtyard and car park.
  // It is opaque for the same reason, and the roads paint on top of it a few
  // lines below.
  //
  // It is laid down first so the forest floor, roads and buildings all paint over
  // it — a paved block is ground the district sits on, not a plate on top.
  //
  // The rects are PAVED_RECTS, not the district parcels. A parcel is a survey
  // rectangle and mostly field; filling it whole paved the emptiness, which is
  // what turned University Quarter into a car park with two sheds in it. PAVED
  // is the built ground only, so an unbuilt corner of a district reads as field.
  // The dashed parcel outline stays, because the parcel is still what names and
  // labels the district.
  ctx.fillStyle = isDark ? "#33302a" : "#cbc3ae";
  for (const p of PAVED_RECTS) {
    const x = p.x * V, y = p.y * V, w = p.w * V, h = p.h * V;
    if (!visible(x, y, w, h, view, 0)) continue;
    ctx.fillRect(x, y, w, h);
  }
  ctx.strokeStyle = isDark ? "rgba(190,168,126,0.34)" : "rgba(120,100,66,0.42)";
  ctx.lineWidth = 1.6;
  ctx.setLineDash([9, 7]);
  for (const p of DISTRICTS) {
    const x = p.x * V, y = p.y * V, w = p.w * V, h = p.h * V;
    if (!visible(x, y, w, h, view, 40)) continue;
    ctx.strokeRect(x, y, w, h);
  }
  ctx.setLineDash([]);

  // Park floor. A rectangle, not an ellipse: the zone is a rect and the trees
  // inside it are scattered on a rect grid, so an elliptical floor left grass
  // showing through at every corner, which read as a stain rather than a wood.
  //
  // Opaque now. It has to be: the city ground below is opaque, so a translucent
  // park floor would mix with the paved lot wherever a park overlaps a district
  // and go muddy. The twelve zones are the city's green — the parks, the green
  // belts and the cemetery — and they should be the clearly green shapes on the
  // map rather than a faint tint the eye has to hunt for.
  ctx.fillStyle = isDark ? "#1c3524" : "#9ac77d";
  for (const f of FORESTS) {
    const x = f.x * V, y = f.y * V, w = f.w * V, h = f.h * V;
    if (!visible(x, y, w, h, view, 0)) continue;
    ctx.fillRect(x, y, w, h);
  }
  // forest labels
  ctx.font = uiFont(7, view.zoom ?? 1);
  ctx.textAlign = "center";
  ctx.globalAlpha = isDark ? 0.5 : 0.42;
  ctx.fillStyle = isDark ? "#8fb88a" : "#2f5a2c";
  for (const f of FORESTS) {
    const cx = (f.x + f.w / 2) * V, cy = (f.y + f.h / 2) * V;
    if (!visible(cx - 60, cy - 10, 120, 20, view, 0)) continue;
    ctx.fillText(f.name, cx, cy);
  }
  // district names, set along the top edge of the parcel like a surveyor's label
  ctx.font = uiFont(10, view.zoom ?? 1);
  ctx.globalAlpha = isDark ? 0.8 : 0.75;
  ctx.fillStyle = isDark ? "#e0bd7c" : "#3d2f18";
  for (const p of DISTRICTS) {
    const cx = (p.x + p.w / 2) * V, cy = p.y * V + 14;
    if (!visible(cx - 70, cy - 10, 140, 20, view, 30)) continue;
    ctx.fillText(p.name.toUpperCase(), cx, cy);
  }
  ctx.globalAlpha = 1;

  // roads — two passes.
  //
  // Split because setLineDash was being called twice per road, inside the loop:
  // 383 visible roads meant 766 calls a frame. setLineDash invalidates the whole
  // stroke state, so that is one of the more expensive calls Canvas2D has, and
  // it was being paid per road to draw a dash pattern that never changes.
  //
  // Pass 1 lays the tarmac, the footway and the edge lines — none of which are
  // dashed. Pass 2 sets the dash once, draws every centre line as a single path,
  // and clears it once. Identical pixels on screen, 2 calls instead of 766.
  for (const r of ROADS) {
    const x = r.x1 * V, y = r.y1 * V;
    const w = (r.x2 - r.x1 + 1) * V, h = (r.y2 - r.y1 + 1) * V;
    if (!visible(x, y, w, h, view, 0)) continue;
    const asphalt = isDark ? "#2b2926" : "#8f8a80";
    const walk = isDark ? "#38352f" : "#d9d4c7";
    ctx.fillStyle = asphalt;
    ctx.fillRect(x, y, w, h);
    // sidewalks inside edges (5px)
    ctx.fillStyle = walk;
    if (w >= h) {
      ctx.fillRect(x, y, w, 5);
      ctx.fillRect(x, y + h - 5, w, 5);
      // edge lines
      ctx.fillStyle = isDark ? "rgba(255,255,255,0.2)" : "rgba(255,255,255,0.5)";
      ctx.fillRect(x, y + 5, w, 1);
      ctx.fillRect(x, y + h - 6, w, 1);
    } else {
      ctx.fillRect(x, y, 5, h);
      ctx.fillRect(x + w - 5, y, 5, h);
      ctx.fillStyle = isDark ? "rgba(255,255,255,0.2)" : "rgba(255,255,255,0.5)";
      ctx.fillRect(x + 5, y, 1, h);
      ctx.fillRect(x + w - 6, y, 1, h);
    }
  }
  ctx.strokeStyle = isDark ? "rgba(216,182,78,0.5)" : "#d8b64e";
  ctx.lineWidth = 2;
  ctx.setLineDash([10, 9]);
  ctx.beginPath();
  for (const r of ROADS) {
    const x = r.x1 * V, y = r.y1 * V;
    const w = (r.x2 - r.x1 + 1) * V, h = (r.y2 - r.y1 + 1) * V;
    if (!visible(x, y, w, h, view, 0)) continue;
    if (w >= h) {
      ctx.moveTo(x + 6, y + h / 2);
      ctx.lineTo(x + w - 6, y + h / 2);
    } else {
      ctx.moveTo(x + w / 2, y + 6);
      ctx.lineTo(x + w / 2, y + h - 6);
    }
  }
  ctx.stroke();
  ctx.setLineDash([]);

  // crosswalks + traffic light corners
  const zebra = isDark ? "rgba(255,255,255,0.3)" : "rgba(255,255,255,0.8)";
  ctx.fillStyle = zebra;
  for (const L of LIGHTS) {
    if (!visible(L.cx - 44, L.cy - 44, 88, 88, view, 0)) continue;
    // across Main/North-style horizontal road (west approach): rungs perpendicular to travel
    for (let i = 0; i < 4; i++) ctx.fillRect(L.cx - 32 + i * 7, L.cy - 15, 4, 30);
    // across vertical road (north approach)
    for (let i = 0; i < 4; i++) ctx.fillRect(L.cx - 15, L.cy - 32 + i * 7, 30, 4);
  }

  // fences (picket). Constant data, so it is built once at module scope rather
  // than re-allocated on every frame — it used to be an array literal inside the
  // draw function, which is 11 objects of garbage per frame for nothing.
  ctx.strokeStyle = isDark ? "#5a5148" : "#f2ede2";
  ctx.lineWidth = 1.4;
  for (const f of FENCES) {
    const x = f.x * V, y = f.y * V, w = f.w * V, h = f.h * V;
    if (!visible(x, y, w, h, view, 0)) continue;
    ctx.strokeRect(x, y, w, h);
  }
  // The inner picket run is dashed and every fence wants the same dash, so it is
  // set once for the lot rather than once per fence — same reason as the road
  // centre lines above.
  ctx.setLineDash([3, 5]);
  for (const f of FENCES) {
    const x = f.x * V, y = f.y * V, w = f.w * V, h = f.h * V;
    if (!visible(x, y, w, h, view, 0)) continue;
    ctx.strokeRect(x + 2, y + 2, w - 4, h - 4);
  }
  ctx.setLineDash([]);

  // grass tufts — one batched stroke for the whole field. Positions are baked
  // in TUFTS above; only the visibility cull runs per frame. (Was: 6 canvas
  // ops per tuft, ~47k ops at full zoom-out.)
  // Grass belongs to the field and the parks, not to a paved lot - that rule
  // is already baked into TUFTS.
  //
  // Skipped entirely below TUFTS_MIN_ZOOM. Batching turned thousands of stroke
  // calls into one, but the 29,557 path ops inside that stroke are still the
  // rasteriser's problem, and at that zoom each lands on less than a quarter of
  // a pixel. The loop itself is guarded, not just its contents.
  if ((view.zoom ?? 1) >= TUFTS_MIN_ZOOM) {
    ctx.strokeStyle = isDark ? "rgba(120,160,110,0.28)" : "rgba(70,120,60,0.35)";
    ctx.lineWidth = 1;
    ctx.beginPath();
    // Only the cells the viewport can reach — see TUFTS_START for why this is
    // not a scan of every tuft on the map.
    const c0 = Math.max(0, Math.min(TUFTS_COLS - 1, (view.l / TUFTS_CELL) | 0));
    const c1 = Math.max(0, Math.min(TUFTS_COLS - 1, (view.r / TUFTS_CELL) | 0));
    const r0 = Math.max(0, Math.min(TUFTS_ROWS - 1, (view.t / TUFTS_CELL) | 0));
    const r1 = Math.max(0, Math.min(TUFTS_ROWS - 1, (view.b / TUFTS_CELL) | 0));
    for (let row = r0; row <= r1; row++) {
      const base = row * TUFTS_COLS;
      for (let cell = base + c0; cell <= base + c1; cell++) {
        const end = TUFTS_START[cell + 1]!;
        for (let k = TUFTS_START[cell]!; k < end; k++) {
          const i = TUFTS_ORDER[k]!;
          const x = TUFTS[i * 2]!, y = TUFTS[i * 2 + 1]!;
          if (!visible(x, y, 2, 2, view, 0)) continue;
          ctx.moveTo(x, y);
          ctx.lineTo(x + 2, y - 4);
          ctx.moveTo(x, y);
          ctx.lineTo(x - 2, y - 3);
        }
      }
    }
    ctx.stroke();
  }
}

