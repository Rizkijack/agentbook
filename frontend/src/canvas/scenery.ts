export type VehicleKind = "car" | "bus" | "truck" | "taxi" | "van" | "pickup";
interface Vehicle {
  /** The stretch of road this unit is currently on, and where it set off from. */
  span: Span;
  from: number;
  d: number;
  x: number; y: number;
  fx: number; fy: number;
  speed: number; base: number;
  color: string;
  kind: VehicleKind;
  axis: "h" | "v";
}

const CAR_COLORS = ["#b83a2e", "#2c6fb3", "#e8e6df", "#2f8f5b", "#d8a12a", "#3c3c42", "#d96b2b", "#2f9ea3", "#7a5cc4", "#c96a9a", "#4a8a6a", "#b8b0a0"];

// Vehicle inventory: 150 units driving the road graph.
//
// The count is 150, not the 300 that was first asked for, and that is a measured
// decision rather than a preference. The fleet this replaces was one loop route
// per road per direction - 738 units - and it was never timed. Now it is: 851
// us/frame, 5.1% of a 60fps budget, nearly all of it the per-vehicle scan over 203
// traffic lights. 150 units at the same per-unit cost is roughly a fifth of that
// while giving real routing behaviour instead of a fixed rectangle.
//
// Kinds are deterministic per index so the street mix is stable frame to frame.
// car = default sedan, taxi = yellow sedan + roof sign, van/pickup = stretched
// sedan, bus/truck = long body (extra axle pair).
const KIND_ORDER: VehicleKind[] = [
  "car", "taxi", "van", "bus", "car", "pickup", "truck", "car",
  "bus", "van", "taxi", "truck", "pickup", "car", "van", "bus",
];

/** How many units the streets carry. See the note above for why 150. */
export const VEHICLE_COUNT = 150;

/** The graph every vehicle drives. Built once; the road table never changes. */
const ROAD_GRAPH = buildGraph(ROADS.map((r) => ({ x1: r.x1, y1: r.y1, x2: r.x2, y2: r.y2 })));

/** Every span, so starting positions spread across the town instead of clumping. */
const ALL_SPANS = ROAD_GRAPH.edges.flat();

/**
 * The rng the fleet routes with.
 *
 * Seeded, never Math.random, for the reason every other generated thing here is
 * seeded: a reload must draw the same traffic, or a resident who watched a
 * particular cart outside the Wet Fleece finds it gone.
 */
let fleetSeed = 0x9e3779b9;
function fleetRng(): number {
  fleetSeed = (Math.imul(fleetSeed, 1664525) + 1013904223) >>> 0;
  return fleetSeed / 4294967296;
}

export const VEHICLES: Vehicle[] = (() => {
  const out: Vehicle[] = [];
  for (let i = 0; i < VEHICLE_COUNT && ALL_SPANS.length > 0; i++) {
    // Deterministic spread: a span chosen by index, not by chance, so the fleet
    // is distributed rather than piled wherever the rng happened to land first.
    const span = ALL_SPANS[(i * 37) % ALL_SPANS.length]!;
    const node = ROAD_GRAPH.nodes[span.from]!;
    const kind = KIND_ORDER[i % KIND_ORDER.length]!;
    // heavy vehicles cruise slightly slower; taxi slightly brisker — same order of magnitude
    const kindFactor = kind === "bus" || kind === "truck" ? 0.82 : kind === "taxi" ? 1.12 : kind === "van" || kind === "pickup" ? 0.95 : 1;
    const base = (44 + h2(i * 13, i * 7) * 30) * kindFactor;
    const color = kind === "taxi" ? "#e8b83a" : CAR_COLORS[i % CAR_COLORS.length]!;
    const d = h2(i + 1, i + 3) * span.len;
    const p = pointOnSpan(span, d, node.x, node.y);
    out.push({
      span,
      from: span.from,
      d,
      x: p.x * V,
      y: p.y * V,
      fx: span.horizontal ? Math.sign(span.dx) || 1 : 0,
      fy: span.horizontal ? 0 : Math.sign(span.dy) || 1,
      speed: base,
      base,
      color,
      kind,
      axis: span.horizontal ? "h" : "v",
    });
  }
  return out;
})();

export type LightState = "red" | "yellow" | "green";

export function lightState(time: number, axis: "h" | "v"): LightState {
  const c = time % 12;
  if (axis === "h") return c < 5 ? "green" : c < 6 ? "yellow" : "red";
  return c < 6 ? "red" : c < 11 ? "green" : "yellow";
}

export function tickScenery(dt: number, time: number): void {
  for (const v of VEHICLES) {
    // brake for a red/yellow light just ahead
    let target = v.base;
    for (const L of LIGHTS) {
      if (v.axis === "h") {
        const dy = Math.abs(L.cy - v.y);
        const ahead = (L.cx - v.x) * v.fx;
        if (dy < 16 && ahead > 2 && ahead < 30 && lightState(time, "h") !== "green") { target = 0; break; }
      } else {
        const dx = Math.abs(L.cx - v.x);
        const ahead = (L.cy - v.y) * v.fy;
        if (dx < 16 && ahead > 2 && ahead < 30 && lightState(time, "v") !== "green") { target = 0; break; }
      }
    }
    v.speed += (target - v.speed) * Math.min(1, dt * (target < v.speed ? 7 : 1.6));

    // Distance is in tiles, speed is px/frame, so scale by the tile size.
    v.d += (v.speed * dt) / V;
    // Two passes is enough: a unit can cross at most one junction per frame at
    // these speeds, and the guard stops a pathological span from looping.
    let guard = 0;
    while (guard++ < 3 && v.d >= v.span.len) {
      v.d -= v.span.len;
      // Routing at runtime: pick a different exit every time, so traffic spreads
      // and two vehicles meet. A dead end reverses, because that is all it can do.
      const exit = nextExit(ROAD_GRAPH, v.span.to, v.from, fleetRng);
      if (!exit) {
        // No way on at all - hold position rather than loop forever.
        v.d = 0;
        break;
      }
      v.from = v.span.from;
      v.span = exit;
      v.axis = exit.horizontal ? "h" : "v";
    }

    const node = ROAD_GRAPH.nodes[v.span.from]!;
    const p = pointOnSpan(v.span, v.d, node.x, node.y);
    v.x = p.x * V;
    v.y = p.y * V;
    v.fx = v.span.horizontal ? Math.sign(v.span.dx) : 0;
    v.fy = v.span.horizontal ? 0 : Math.sign(v.span.dy);
  }
}

