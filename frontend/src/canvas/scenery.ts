// --- what a tile is ---------------------------------------------------------
/**
 * How likely a tree survives, per kind of place.
 *
 * This used to be one radial number per tile: a clear disc around the square, a
 * thinner ring, and then 0.3 for every remaining tile on the map. That last
 * clause was the whole problem. 0.3 of 74,550 candidates is ~22,000 trees
 * spread evenly over everything that was not the town centre, densest where the
 * map was widest, so the region outside the districts carried a woodland
 * scatter from edge to edge and the whole-map view read as a meadow with roads
 * in it. Cutting FORESTS from 30 zones to 12 moved the number on the metric and
 * changed nothing a viewer could see, because the zones were never the green
 * mass in the first place.
 *
 * It was then rekeyed to the nine district parcels, which fixed the countryside
 * but kept a defect of its own: BLOCK was "inside a parcel", so block-interior
 * survival was 0.03 on tiles that a 3% rate made invisible in the number and
 * very visible on screen. The parcels are surveyed rectangles far larger than
 * what is built, and a 0.03 chance over ~50,000 block tiles is not a handful of
 * trees, it is hundreds of pines standing on pavement.
 *
 * Density now follows the paved ground, because that is the honest test. A tile
 * that the pavement bake marks paved is city ground — carriageway, forecourt,
 * yard or lot — and a tree on it is wrong at any probability, so the tree loop
 * asks PAVED and drops the tile outright rather than rolling a die. What is
 * left is the three kinds of unbuilt ground: open country outside the parcels,
 * the parcels' own unbuilt remainder (the EDGE band below), and the parks.
 */
export const ZONE = {
  COUNTRY: 0, // open country: hedges and rough ground, not a wood
  EDGE: 1,    // unbuilt ground inside a district parcel: gardens, rough grass
  PARK: 2,    // the parks, green belts and the cemetery
} as const;

/** Survival probability, indexed by the ZONE constants above. */
const GREEN: readonly number[] = [
  0.05, // COUNTRY
  0.10, // EDGE   — the open ground a district was surveyed around
  0.62, // PARK   — a park is meant to be green
];

function inForest(tx: number, ty: number): boolean {
  for (const f of FORESTS) {
    if (tx >= f.x && tx < f.x + f.w && ty >= f.y && ty < f.y + f.h) return true;
  }
  return false;
}

/** The district parcel a tile stands in, or null if it is open country. */
function urbanParcel(tx: number, ty: number): { x: number; y: number; w: number; h: number } | null {
  for (const p of DISTRICT_PARCELS) {
    if (tx >= p.x && tx < p.x + p.w && ty >= p.y && ty < p.y + p.h) return p;
  }
  return null;
}

/**
 * The footprints that are built rather than open ground.
 *
 * Food and Water locations are meadows, fields, ponds and the river. They sit
 * inside the town parcel and they are drawn as fields, so paving around them
 * would put tarmac under a wheat field. The same split is what
 * frontend/test/scenery.test.ts calls BUILT_LOCS, and it is why this list
 * exists rather than reusing all of LOCATIONS.
 */
const BUILT: typeof LOCATIONS = LOCATIONS.filter((l) => l.category !== "Food" && l.category !== "Water");

/**
 * How far out from the built ground the pavement reaches, in tiles.
 *
 * Measured, not guessed. At 8 the downtown parcel is 93% paved and the outer
 * districts 58-87%, so the town centre stays a city and the fields at the edge
 * of a district come back; at 12 the outer districts are 77-93% paved, which is
 * the void this bake exists to remove. 8 tiles is also 128px at V=16, about a
 * forecourt and a front garden — deep enough to read as a block, shallow enough
 * that the middle of an empty block stays green.
 */
const PAVE_REACH = 8;

/**
 * Distance in tiles from every tile to the nearest road or built footprint,
 * baked once. A two-sweep chamfer transform over the 672,000-tile grid: forward
 * with the north-west neighbours, backward with the south-east. Chebyshev on
 * purpose — the metric is rectangular, so the paved fringe comes out as bands
 * parallel to the street rather than as rings round each building.
 *
 * The answer depends only on the tile and the ground fill asks about 60,000 of
 * them per frame, so this cannot be re-derived per draw.
 */
const BUILT_DIST: Int32Array = (() => {
  const FAR = PAVE_REACH + 1;
  const d = new Int32Array(Pe * vt).fill(FAR);
  // Only footprints seed this one. Roads are handled by ROAD_DIST below, at a
  // much smaller reach, and mixing them here would give every carriageway an
  // 8-tile lot and pave the map.
  for (const l of BUILT) {
    for (let y = Math.max(0, l.y); y <= Math.min(vt - 1, l.y + l.h - 1); y++) {
      for (let x = Math.max(0, l.x); x <= Math.min(Pe - 1, l.x + l.w - 1); x++) d[y * Pe + x] = 0;
    }
  }
  for (let y = 0; y < vt; y++) {
    for (let x = 0; x < Pe; x++) {
      let m = d[y * Pe + x]!;
      if (x > 0) m = Math.min(m, d[y * Pe + x - 1]! + 1);
      if (y > 0) m = Math.min(m, d[(y - 1) * Pe + x]! + 1);
      if (x > 0 && y > 0) m = Math.min(m, d[(y - 1) * Pe + x - 1]! + 1);
      if (x < Pe - 1 && y > 0) m = Math.min(m, d[(y - 1) * Pe + x + 1]! + 1);
      d[y * Pe + x] = m;
    }
  }
  for (let y = vt - 1; y >= 0; y--) {
    for (let x = Pe - 1; x >= 0; x--) {
      let m = d[y * Pe + x]!;
      if (x < Pe - 1) m = Math.min(m, d[y * Pe + x + 1]! + 1);
      if (y < vt - 1) m = Math.min(m, d[(y + 1) * Pe + x]! + 1);
      if (x < Pe - 1 && y < vt - 1) m = Math.min(m, d[(y + 1) * Pe + x + 1]! + 1);
      if (x > 0 && y < vt - 1) m = Math.min(m, d[(y + 1) * Pe + x - 1]! + 1);
      d[y * Pe + x] = m;
    }
  }
  return d;
})();

/**
 * How far out from a carriageway the footway reaches, in tiles.
 *
 * Small on purpose, and that is the whole design. The apron exists to stop the
 * tarmac meeting grass — two or three tiles is a kerb, a footway and a verge.
 * At 8 (the value buildings get) a grid with 369 segments dilates into one
 * continuous sheet and the entire map becomes pavement, which is the defect the
 * district parcels were introduced to prevent.
 *
 * 3 was picked from the measurement, not by taste: it takes road coverage from
 * 16.5% of road tiles to 100% while keeping the paved share of the world in the
 * low tens of percent rather than the 44.7% that a single shared reach produced.
 */
const ROAD_REACH = 2;

/**
 * Distance to the nearest carriageway, driveway or spur, baked once.
 *
 * A second chamfer transform over the same grid, kept separate from BUILT_DIST
 * because the two want different reaches. Running one transform for both is what
 * forced a compromise: either roads had no apron, or everything did.
 */
const ROAD_DIST: Int32Array = (() => {
  const FAR = ROAD_REACH + 1;
  const d = new Int32Array(Pe * vt).fill(FAR);
  const mark = (x1: number, y1: number, x2: number, y2: number) => {
    for (let y = Math.max(0, y1); y <= Math.min(vt - 1, y2); y++) {
      for (let x = Math.max(0, x1); x <= Math.min(Pe - 1, x2); x++) d[y * Pe + x] = 0;
    }
  };
  for (const r of ROADS) mark(r.x1, r.y1, r.x2, r.y2);
  // Driveways are carriageway as far as this test is concerned — a lane is a lane,
  // and it needs the same footway at its edges or it reads as a scar in the grass.
  for (const s of ACCESS_SPURS) {
    mark(Math.min(s.x1, s.x2), Math.min(s.y1, s.y2), Math.max(s.x1, s.x2), Math.max(s.y1, s.y2));
  }
  for (let y = 0; y < vt; y++) {
    for (let x = 0; x < Pe; x++) {
      let m = d[y * Pe + x]!;
      if (x > 0) m = Math.min(m, d[y * Pe + x - 1]! + 1);
      if (y > 0) m = Math.min(m, d[(y - 1) * Pe + x]! + 1);
      if (x > 0 && y > 0) m = Math.min(m, d[(y - 1) * Pe + x - 1]! + 1);
      if (x < Pe - 1 && y > 0) m = Math.min(m, d[(y - 1) * Pe + x + 1]! + 1);
      d[y * Pe + x] = m;
    }
  }
  for (let y = vt - 1; y >= 0; y--) {
    for (let x = Pe - 1; x >= 0; x--) {
      let m = d[y * Pe + x]!;
      if (x < Pe - 1) m = Math.min(m, d[y * Pe + x + 1]! + 1);
      if (y < vt - 1) m = Math.min(m, d[(y + 1) * Pe + x]! + 1);
      if (x < Pe - 1 && y < vt - 1) m = Math.min(m, d[(y + 1) * Pe + x + 1]! + 1);
      if (x > 0 && y < vt - 1) m = Math.min(m, d[(y + 1) * Pe + x - 1]! + 1);
      d[y * Pe + x] = m;
    }
  }
  return d;
})();

/**
 * The paved ground, tile by tile — this is what "the city" now means.
 *
 * It used to be the whole district parcel, painted in one opaque fillRect per
 * district. The parcels are survey rectangles, not built area: University
 * Quarter's is 184x46 tiles and holds two buildings, so the fill made a car
 * park with two sheds, and on the dark theme the empty lot was a light-grey
 * rectangle standing against dark green because light pavement on dark ground
 * has far more contrast than dark pavement on light ground.
 *
 * So pavement is the built ground and nothing else: within PAVE_REACH tiles of a
 * road or a footprint, and not inside a park (the park floor paints over it, and
 * a park is not a car park). Because every tile is only ever paved by being near
 * a road or a footprint, the bake cannot produce a paved region that contains
 * neither — the property is structural, not a check that has to be re-run.
 *
 * The parcel test came out, and it was wrong by a wide margin. Measured: 6,890 of
 * the 41,852 road tiles were paved, so 83.5% of the carriageway had no paved
 * ground beside it at all. The nine parcels are 12.1% of the world and were
 * surveyed for the 5x-era map, while the road grid grew to 369 segments reaching
 * x=1019 and y=592 — so a suburban street rendered as a strip of tarmac with
 * grass hard against both kerbs. No verge, no lot, no footway. The road surface
 * itself was always opaque, which is why this hid so well: the carriageway looked
 * correct and the ground it should sit in was simply never drawn.
 *
 * Simply deleting the parcel test was tried and reverted, and the measurement is
 * why: it paved 300,426 tiles, 44.7% of the world. Dilation by 8 around a grid
 * this dense merges into one continuous sheet, so the whole map became the car
 * park the parcel test existed to prevent. Removing the brake is not a fix.
 *
 * What a road and a building need are different things, and that is the fix. A
 * road wants a narrow footway and a verge — a few tiles, enough to stop the
 * tarmac meeting the grass. A building wants a forecourt and a yard — deep
 * enough to read as a block. So there are two distances: ROAD_REACH is the apron,
 * PAVE_REACH stays the block depth, and a tile is paved if either one reaches it.
 */
export const PAVED: Uint8Array = (() => {
  const m = new Uint8Array(Pe * vt);
  for (let ty = 0; ty < vt; ty++) {
    for (let tx = 0; tx < Pe; tx++) {
      const i = ty * Pe + tx;
      if (ROAD_DIST[i]! > ROAD_REACH && BUILT_DIST[i]! > PAVE_REACH) continue;
      // A footprint still has to belong to somewhere. Without the parcel test a
      // lone farmhouse 40 tiles outside the nearest district paved a 16-tile
      // apron around itself, which is a house with a car park rather than a farm.
      if (BUILT_DIST[i]! <= PAVE_REACH && !urbanParcel(tx, ty)) {
        if (ROAD_DIST[i]! > ROAD_REACH) continue;
      }
      if (inForest(tx, ty)) continue;
      m[i] = 1;
    }
  }
  return m;
})();

interface TileRect { x: number; y: number; w: number; h: number; }

/**
 * The paved area as maximal rectangles, in tiles.
 *
 * PAVED is a mask, but the ground fill wants rectangles: 62,000 fillRects of
 * 16px each per frame is a different renderer. A greedy right-then-down merge
 * over the mask collapses it to ~120, which is fewer rects than the nine
 * districts it replaced.
 */
export const PAVED_RECTS: TileRect[] = (() => {
  const taken = new Uint8Array(Pe * vt);
  const out: TileRect[] = [];
  for (let ty = 0; ty < vt; ty++) {
    for (let tx = 0; tx < Pe; tx++) {
      const i = ty * Pe + tx;
      if (!PAVED[i] || taken[i]) continue;
      let w = 1;
      while (tx + w < Pe && PAVED[i + w] && !taken[i + w]) w++;
      let h = 1;
      grow: while (ty + h < vt) {
        for (let k = 0; k < w; k++) if (!PAVED[(ty + h) * Pe + tx + k] || taken[(ty + h) * Pe + tx + k]) break grow;
        h++;
      }
      for (let y = 0; y < h; y++) for (let k = 0; k < w; k++) taken[(ty + y) * Pe + tx + k] = 1;
      out.push({ x: tx, y: ty, w, h });
    }
  }
  return out;
})();

/**
 * The zone of every tile, baked once — the same reasoning as BLOCKED above. The
 * answer depends only on the tile and the tree loop asks 74,550 times, so it is
 * not worth re-deriving. Note what is NOT here: a zone for paved ground. Paving
 * is its own array now, and a tile that is paved has no tree survival at all
 * rather than a small one.
 */
const ZONES: Uint8Array = (() => {
  const m = new Uint8Array(Pe * vt);
  for (let ty = 0; ty < vt; ty++) {
    for (let tx = 0; tx < Pe; tx++) {
      m[ty * Pe + tx] = inForest(tx, ty) ? ZONE.PARK : urbanParcel(tx, ty) ? ZONE.EDGE : ZONE.COUNTRY;
    }
  }
  return m;
})();

export interface Tree { x: number; y: number; kind: "oak" | "pine" | "bush" | "birch"; s: number; }

export const TREES: Tree[] = [];
// One candidate per 3x3 tiles across the whole grid. This used to be hardcoded
// to `gx < 209, gy < 127`; on the 5x map that covered 4% of the world, so the
// forests east, south and west of town were bare ground.
for (let gx = 1; gx < Pe - 1; gx += 3) {
  for (let gy = 1; gy < vt - 1; gy += 3) {
    const jx = gx + Math.floor(h2(gx, gy) * 3) - 1;
    const jy = gy + Math.floor(h2(gy + 7, gx) * 3) - 1;
    if (!natureFree(jx, jy)) continue;
    // A tree on pavement is wrong at any survival rate, so this is a gate and not
    // a probability: the ground fill reads the same PAVED array, which is what
    // stops the two from disagreeing about where the city is.
    if (PAVED[jy * Pe + jx]) continue;
    const r = h2(jx * 7 + 3, jy * 11 + 5);
    if (r > GREEN[ZONES[jy * Pe + jx]]!) continue;
    const k = h2(jy * 5 + 1, jx * 13 + 9);
    const kind: Tree["kind"] = k < 0.4 ? "oak" : k < 0.68 ? "pine" : k < 0.88 ? "bush" : "birch";
    TREES.push({ x: jx * V + 8 + (h2(jx + 2, jy + 4) - 0.5) * 8, y: jy * V + 14, kind, s: 0.8 + h2(jx, jy + 3) * 0.55 });
  }
}

